def test_matches_machine_ignoring_the_at_suffix():
    presets = [{"name": "Voron 2.4 350 @workshop", "rel": "voron.json",
                "printer_model": "Voron 2.4", "printer_variant": "0.4"}]
    info = threemf.ThreeMfInfo(printer="Voron 2.4 350 @warehouse")
    assert threemf.match_machine(presets, info) is presets[0]
    # a different size in the same base name is a different machine, not a fuzzy match
    assert threemf.match_machine(presets, threemf.ThreeMfInfo(printer="Voron 2.4 500 @warehouse")) is None


def test_ambiguous_machine_match_is_none():
    keep = {"name": "Voron 2.4 350 @workshop", "rel": "a.json",
            "printer_model": "Voron 2.4", "printer_variant": "0.4"}
    other = {"name": "Voron 2.4 350 @office", "rel": "b.json",
             "printer_model": "Voron 2.4", "printer_variant": "0.6"}
    info = threemf.ThreeMfInfo(printer="Voron 2.4 350 @warehouse", printer_variant="0.6")
    # both are base-equal; only one declares the file's variant, so that breaks the tie
    assert threemf.match_machine([keep, other], info) is other
    # ... and once neither does, the file is ambiguous: fall back, never guess
    assert threemf.match_machine([keep, dict(other, printer_variant="0.4")], info) is None


def test_matches_process_ignoring_the_at_suffix():
    vendor_a = {"name": "0.20mm Standard @Vendor A", "rel": "a.json",
                "compatible_printers": ["Vendor A 0.4 nozzle"]}
    vendor_b = {"name": "0.20mm Standard @Vendor B", "rel": "b.json",
                "compatible_printers": ["Vendor B 0.4 nozzle"]}
    info = threemf.ThreeMfInfo(process="0.20mm Standard @Vendor C")
    machine = {"name": "Vendor B 0.4 nozzle", "rel": "vendor-b.json"}
    # base-equal for both; the one compatible with the matched machine wins
    assert threemf.match_process([vendor_a, vendor_b], info, machine) is vendor_b
    # without a matched machine nothing breaks the tie
    assert threemf.match_process([vendor_a, vendor_b], info, None) is None


def test_process_falls_back_to_the_machine_default_print_profile(datadir):
    """A file that names no local process gets the machine's own `default_print_profile`.

    The machine row is the production one — `prof.summarise`, the same row ``app.main``
    passes to `match_process` — not a hand-written dict. A hand-written row with the key
    added used to pass while production never exported it, so the fallback was unreachable
    there and this test proved nothing. The decoy process sorts first, so "the first preset
    in the datadir" is a different answer from "the machine's default".
    """
    machine_file = datadir / MACHINE_REL
    machine = prof.summarise(machine_file, "machine", datadir)
    default = json.loads(machine_file.read_text())["default_print_profile"]
    assert (machine["name"], machine["rel"]) == (MACHINE_NAME, MACHINE_REL)
    assert machine.get("default_print_profile") == default == PROCESS_NAME
    (datadir / "system/Custom/process/aaa-draft.json").write_text(json.dumps({
        "type": "process", "name": "0.28mm Draft @Generic Klipper", "instantiation": "true"}))
    processes = prof.list_presets(datadir)["process"]
    assert [row["name"] for row in processes][0] == "0.28mm Draft @Generic Klipper"

    unrelated = threemf.ThreeMfInfo(process="Totally Unrelated Profile")
    assert threemf.match_process(processes, unrelated, machine)["name"] == default
    # a file that names no process at all still gets the machine's default
    assert threemf.match_process(processes, threemf.ThreeMfInfo(), machine)["name"] == default
    # no default declared is not an error: the caller keeps the current process
    undeclared = {key: value for key, value in machine.items() if key != "default_print_profile"}
    assert threemf.match_process(processes, unrelated, undeclared) is None


def test_chooses_the_printer_paired_with_the_machine():
    """Pairing the matched machine is what decides; a shared-word name cannot decide.

    ``_printer_score``'s token match returns 40 and `PRINTER_THRESHOLD` is 80, so "BBL X1C
    printer" for a file naming "BBL X1C 0.4 nozzle" is a hint only: it never competes with
    the paired row, and on its own it is refused instead of guessed.
    """
    fuzzy = {"id": "aaaaaaaaaaaa", "name": "BBL X1C printer", "profiles": None}
    paired = {"id": "bbbbbbbbbbbb", "name": "Warehouse Klipper",
              "profiles": {"machine": MACHINE_REL, "process": None}}
    machine = {"name": MACHINE_NAME, "rel": MACHINE_REL}
    info = threemf.ThreeMfInfo(printer="BBL X1C 0.4 nozzle")
    assert threemf.choose_printer([fuzzy, paired], info, machine, "aaaaaaaaaaaa") == (
        "bbbbbbbbbbbb", [])
    kept, notes = threemf.choose_printer([fuzzy], info, machine, "aaaaaaaaaaaa")
    assert kept is None
    assert notes == ["printer 'BBL X1C 0.4 nozzle' from the 3MF is not configured here; "
                     "kept 'BBL X1C printer'"]


def test_prefers_the_current_printer_on_a_tie():
    """Two rows tied above `PRINTER_THRESHOLD`: the current one wins, else the file is ambiguous."""
    rows = [{"id": "aaaaaaaaaaaa", "name": "First", "profiles": {"machine": MACHINE_REL}},
            {"id": "bbbbbbbbbbbb", "name": "Second", "profiles": {"machine": MACHINE_REL}}]
    machine = {"name": MACHINE_NAME, "rel": MACHINE_REL}
    info = threemf.ThreeMfInfo(printer="Neither Name")
    assert threemf.choose_printer(rows, info, machine, "bbbbbbbbbbbb") == ("bbbbbbbbbbbb", [])
    ambiguous = ("printer 'Neither Name' from the 3MF matches more than one configured "
                 "printer; kept '{}'")
    assert threemf.choose_printer(rows, info, machine, None) == (None, [ambiguous.format("none")])
    assert threemf.choose_printer(rows, info, machine, "cccccccccccc") == (
        None, [ambiguous.format("cccccccccccc")])


def test_unknown_printer_keeps_the_selection_and_returns_a_note():
    rows = [{"id": "aaaaaaaaaaaa", "name": "Configured Printer", "profiles": None}]
    machine = {"name": MACHINE_NAME, "rel": MACHINE_REL}
    info = threemf.ThreeMfInfo(printer="Unseen Machine 0.4")
    assert threemf.choose_printer(rows, info, machine, "aaaaaaaaaaaa") == (
        None, ["printer 'Unseen Machine 0.4' from the 3MF is not configured here; "
               "kept 'Configured Printer'"])
    # an unknown current id is reported as-is, never invented
    _, notes = threemf.choose_printer(rows, info, machine, "cccccccccccc")
    assert notes == ["printer 'Unseen Machine 0.4' from the 3MF is not configured here; "
                     "kept 'cccccccccccc'"]
    # a file that names no printer changes nothing and says nothing
    assert threemf.choose_printer(rows, threemf.ThreeMfInfo(), machine, "aaaaaaaaaaaa") == (None, [])


